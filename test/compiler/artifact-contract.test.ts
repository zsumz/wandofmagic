import { describe, expect, it } from 'vitest';

import {
    TRUSTED_MAPPER_FORMAT_VERSION,
    emitTrustedMapperModule,
} from '../../src/compiler/index.js';
import { projectionConformanceSpell } from './projection/conformance-fixture.js';

describe('trusted mapper artifact contract', () => {
    it('publishes a versioned, immutable artifact', () => {
        const artifact = emitTrustedMapperModule(projectionConformanceSpell);

        expect(artifact.formatVersion).toBe(TRUSTED_MAPPER_FORMAT_VERSION);
        expect(artifact.source).toContain(
            `Generated by wandofmagic/compiler format ${String(TRUSTED_MAPPER_FORMAT_VERSION)}`,
        );
        expect(Object.isFrozen(artifact)).toBe(true);
        expect(Object.isFrozen(artifact.bindings)).toBe(true);
        expect(Object.isFrozen(artifact.bindingDescriptions)).toBe(true);
        expect(artifact.bindingDescriptions.every(Object.isFrozen)).toBe(true);
    });

    it('emits deterministic source and binding metadata', () => {
        const first = emitTrustedMapperModule(projectionConformanceSpell);
        const second = emitTrustedMapperModule(projectionConformanceSpell);

        expect(second.source).toBe(first.source);
        expect(second.bindingDescriptions).toEqual(first.bindingDescriptions);
        expect(second.bindings).toEqual(first.bindings);
    });
});
