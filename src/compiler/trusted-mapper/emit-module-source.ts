import { TRUSTED_MAPPER_FORMAT_VERSION } from './emitted-mapper.js';

export function emitModuleSource(
    runtimeLines: readonly string[],
    factoryLines: readonly string[],
    exportedFactory: string,
): string {
    const lines = [
        `// Generated by wandofmagic/compiler format ${String(TRUSTED_MAPPER_FORMAT_VERSION)} `
            + 'for trusted input and discarded receipts.',
        ...runtimeLines,
        '',
        ...factoryLines,
        '',
        `export { ${exportedFactory} as createTrustedMapper };`,
        '',
    ];
    return lines.join('\n');
}
