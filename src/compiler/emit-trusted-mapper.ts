import type { Spell } from '../core/spell.js';
import { getFlatProgram } from '../runtime/flat-program-registry.js';
import { CompilerError } from './compiler-error.js';
import { emitOperation } from './emit-operation.js';
import { emitStructuralProjection } from './emit-structural-projection.js';
import type { TrustedMapperModule } from './emitted-mapper.js';
import { createEmitterState } from './emitter-state.js';
import { generatedRuntimeSource } from './generated-runtime-source.js';
import { analyzeStructuralProgram } from './structural-program.js';

/** Emit an ESM factory specialized for trusted input with discarded receipts. */
export function emitTrustedMapperModule<Input extends object, Output extends object>(
    spell: Spell<Input, Output>,
): TrustedMapperModule {
    const program = getFlatProgram(spell);
    if (program === undefined) {
        throw new CompilerError(
            'unsupported_spell',
            'Static mapper emission requires a supported flat spell built by this package instance.',
        );
    }

    const structural = analyzeStructuralProgram(program);
    const state = createEmitterState();
    const operationLines: string[] = [];
    for (let index = 0; index < structural.middle.length; index += 1) {
        const instruction = structural.middle[index];
        if (instruction !== undefined) {
            operationLines.push(...emitOperation(instruction, index, state));
        }
    }
    const includeIsoDate = structural.middle.some((instruction) =>
        instruction.kind === 'coerce' && instruction.coercer.kind === 'iso-date');
    const source = emitModuleSource(
        emitStructuralProjection(structural),
        operationLines,
        state.bindingDescriptions,
        includeIsoDate,
    );

    return Object.freeze({
        bindingDescriptions: Object.freeze([...state.bindingDescriptions]),
        bindings: Object.freeze([...state.bindings]),
        mode: 'trusted-discard',
        source,
    });
}

function emitModuleSource(
    structuralLines: readonly string[],
    operationLines: readonly string[],
    bindings: ReadonlyArray<{ readonly index: number; readonly kind: string }>,
    includeIsoDate: boolean,
): string {
    const lines = [
        '// Generated by wandofmagic/compiler for trusted input and discarded receipts.',
        ...generatedRuntimeSource(includeIsoDate),
        '',
        'export function createTrustedMapper($bindings, $WandError) {',
        `    if (!Array.isArray($bindings) || $bindings.length !== ${String(bindings.length)}) {`,
        '        throw new TypeError("Generated Wandofmagic mapper bindings do not match the plan.");',
        '    }',
        '    if (typeof $WandError !== "function") {',
        '        throw new TypeError("Generated Wandofmagic mappers require the WandError constructor.");',
        '    }',
    ];
    for (const binding of bindings) {
        const name = `$binding${String(binding.index)}`;
        lines.push(`    const ${name} = $bindings[${String(binding.index)}];`);
        if (binding.kind !== 'default') {
            lines.push(`    if (typeof ${name} !== "function") {`);
            lines.push('        throw new TypeError("A generated Wandofmagic callable binding is invalid.");');
            lines.push('    }');
        }
    }
    lines.push('    return function run(input) {');
    lines.push(...structuralLines);
    lines.push(...operationLines);
    lines.push('        return $value;');
    lines.push('    };');
    lines.push('}');
    lines.push('');
    return lines.join('\n');
}
